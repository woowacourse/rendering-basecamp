import { moviesApi } from "@/api/movies";
import MovieHomeContent from "@/components/common/MovieHomeContent";
import { MovieItem } from "@/types/Movie.types";
import { GetServerSideProps, InferGetServerSidePropsType } from "next";
import Head from "next/head";

export const getServerSideProps = (async () => {
  // 외부 API에서 데이터를 가져옵니다.
  const res = await moviesApi.getPopular();
  // props를 통해 페이지에 데이터를 전달합니다.
  return {
    props: { movies: res.data.results },
  };
}) satisfies GetServerSideProps<{ movies: MovieItem[] }>;

export default function Home({
  movies,
}: InferGetServerSidePropsType<typeof getServerSideProps>) {
  return (
    <>
      <Head>
        {/* 루트 페이지의 메타데이터를 따로 설정하는 부분*/}
        <meta
          name="google-site-verification"
          content="ctZsSM914QXHgPUuFZtYfDcClWsHClMtPoMaR0QjfZk"
        />
        <title>Create Next App</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <MovieHomeContent movies={movies} />
    </>
  );
}
